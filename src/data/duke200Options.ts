function buildAll10000Options(): DukeCatalogOption[] {
  const result: DukeCatalogOption[] = [];
  let nextId = 1;

  for (const matrix of MATRICES) {
    // 1. Add the 25 flagship handcrafted seeds first
    for (const [title, description, prompt] of matrix.seeds) {
      const id = nextId++;
      result.push({
        id,
        category: matrix.category,
        mode: matrix.mode,
        title,
        description,
        prompt,
        searchText: normalizeSearch(`${id} ${title} ${description} ${matrix.category}`),
      });
    }

    // 2. Add 35 × 35 = 1,225 unique combinations (total 1,250 per category × 8 = 10,000 exact)
    for (let b = 0; b < matrix.bases.length; b += 1) {
      const base = matrix.bases[b];
      for (let m = 0; m < matrix.modifiers.length; m += 1) {
        const mod = matrix.modifiers[m];
        const id = nextId++;
        const title = `${base} — ${mod}`;
        const description = matrix.makeDescription(base, mod);
        const prompt = matrix.makePrompt(base, mod);
        result.push({
          id,
          category: matrix.category,
          mode: matrix.mode,
          title,
          description,
          prompt,
          searchText: normalizeSearch(`${id} ${title} ${description} ${matrix.category}`),
        });
      }
    }
  }

  return result;
}

export const DUKE_10000_OPTIONS: DukeCatalogOption[] = buildAll10000Options();
